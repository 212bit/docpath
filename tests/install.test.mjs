  it('install --hooks writes an executable pre-commit hook that runs docpath check', () => {
    const cwd = mkWorkspace();
    mkdirSync(join(cwd, '.git'), { recursive: true });

    run(`install --cwd ${cwd} --target codex --hooks`, cwd);

    const hookPath = join(cwd, '.git', 'hooks', 'pre-commit');
    assert.equal(existsSync(hookPath), true);
    assert.ok((statSync(hookPath).mode & 0o111) !== 0, 'pre-commit hook should be executable');
    const hook = readFileSync(hookPath, 'utf-8');
    assert.match(hook, /Generated by docpath install --hooks/);
    assert.match(hook, /\.\/\.docpath\/bin\/docpath check/);
    assert.match(hook, /docpath check/);
    assert.match(hook, /node \.\/dist\/index\.js check/);
    rmSync(cwd, { recursive: true, force: true });
  });

  it('install --hooks preserves existing pre-commit hook unless --force is used', () => {
    const cwd = mkWorkspace();
    const hooksDir = join(cwd, '.git', 'hooks');
    mkdirSync(hooksDir, { recursive: true });
    const hookPath = join(hooksDir, 'pre-commit');
    writeFileSync(hookPath, '#!/usr/bin/env sh\necho custom\n');

    const skipped = run(`install --cwd ${cwd} --target codex --hooks`, cwd);
    assert.match(skipped, /pre-commit hook/);
    assert.match(skipped, /使用 --force 覆盖/);
    assert.equal(readFileSync(hookPath, 'utf-8'), '#!/usr/bin/env sh\necho custom\n');

    run(`install --cwd ${cwd} --target codex --hooks --hook-mode agent-done --force`, cwd);
    const overwritten = readFileSync(hookPath, 'utf-8');
    assert.match(overwritten, /\.\/\.docpath\/bin\/docpath agent done/);
    assert.match(overwritten, /docpath agent done/);
    rmSync(cwd, { recursive: true, force: true });
  });

  it('install --hooks rejects invalid hook mode loudly', () => {
    const cwd = mkWorkspace();
    mkdirSync(join(cwd, '.git'), { recursive: true });

    const failed = runResult(`install --cwd ${cwd} --hooks --hook-mode both`, cwd);

    assert.equal(failed.code, 1);
    assert.match(failed.out, /未知 hook mode: both/);
    assert.match(failed.out, /check \| agent-done/);
    rmSync(cwd, { recursive: true, force: true });
  });

  it('does not overwrite existing protocol files without --force and prints a diff hint', () => {
    const cwd = mkWorkspace();
    writeFileSync(join(cwd, 'OPENCODE.md'), '# Custom Agent Rules\n\nDo not overwrite.\n');

    const output = run(`install --cwd ${cwd} --target opencode`, cwd);
    const unchanged = readFileSync(join(cwd, 'OPENCODE.md'), 'utf-8');

    assert.match(output, /差异预览/);
    assert.match(output, /使用 --force 覆盖/);
    assert.equal(unchanged, '# Custom Agent Rules\n\nDo not overwrite.\n');

    run(`install --cwd ${cwd} --target opencode --force`, cwd);
    const overwritten = readFileSync(join(cwd, 'OPENCODE.md'), 'utf-8');
    assert.match(overwritten, /docpath next --agent/);
    assert.match(overwritten, /docpath agent done --step/);
    assert.doesNotMatch(overwritten, /agent enter --step/);
    assert.doesNotMatch(overwritten, /Do not overwrite/);
    rmSync(cwd, { recursive: true, force: true });
  });

  it('does not overwrite existing Codex Skill without --force', () => {
    const cwd = mkWorkspace();
    const skillDir = join(cwd, '.codex', 'skills', 'docpath');
    mkdirSync(skillDir, { recursive: true });
    const skillPath = join(skillDir, 'SKILL.md');
    writeFileSync(skillPath, '# Custom Skill\n');

    const output = run(`install --cwd ${cwd} --target codex`, cwd);
    assert.match(output, /Codex Skill/);
    assert.match(output, /使用 --force 覆盖/);
    assert.equal(readFileSync(skillPath, 'utf-8'), '# Custom Skill\n');

    run(`install --cwd ${cwd} --target codex --force`, cwd);
    const overwritten = readFileSync(skillPath, 'utf-8');
    assert.match(overwritten, /name: docpath/);
    assert.match(overwritten, /docpath status --agent/);
    assert.doesNotMatch(overwritten, /Custom Skill/);
    rmSync(cwd, { recursive: true, force: true });
  });
