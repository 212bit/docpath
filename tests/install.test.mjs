import { describe, it } from 'node:test';
import assert from 'node:assert/strict';
import { execSync } from 'child_process';
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, existsSync, rmSync, statSync } from 'fs';
import { join } from 'path';
import { tmpdir } from 'os';

const BIN = new URL('../dist/index.js', import.meta.url).pathname;
const TEMPLATE_COMMANDS_DIR = new URL('../templates/commands/', import.meta.url).pathname;

const CLAUDE_EXPOSED_COMMANDS = [
  'agent-done',
  'agent-enter',
  'agent-handoff',
  'agent-step',
  'brainstorm',
  'check',
  'compact',
  'config',
  'context',
  'continue',
  'debug',
  'diff',
  'discover',
  'disclosure',
  'docs',
  'export',
  'go',
  'init',
  'install',
  'journal',
  'learn',
  'next',
  'plan',
  'refine',
  'resume',
  'reveal',
  'review',
  'run',
  'stats',
  'status',
  'tdd',
  'unlink',
  'write-journal',
  'write-plan',
  'write-spec',
];

function mkWorkspace() {
  const cwd = mkdtempSync(join(tmpdir(), 'dp-install-'));
  const dp = join(cwd, '.docpath');
  mkdirSync(join(dp, 'workspace'), { recursive: true });
  writeFileSync(join(dp, 'config.yaml'), 'project:\n  name: install-test\n');
  writeFileSync(join(dp, 'workspace', 'current.md'), '# Current\n');
  return cwd;
}

function run(args, cwd) {
  return execSync(`node ${BIN} ${args}`, { cwd, encoding: 'utf-8', timeout: 20000 });
}

describe('install agent adapters', () => {
  it('claude target installs slash commands for the DocPath lifecycle', () => {
    const cwd = mkWorkspace();
    run(`install --cwd ${cwd} --target claude`, cwd);

    const commandsDir = join(cwd, '.claude', 'commands');
    assert.equal(existsSync(join(cwd, 'CLAUDE.md')), true);
    assert.equal(existsSync(join(cwd, '.docpath', 'bin', 'docpath')), true);
    assert.equal(existsSync(join(cwd, 'AGENTS.md')), false);
    assert.equal(existsSync(join(commandsDir, 'docpath-next.md')), true);
    assert.equal(existsSync(join(commandsDir, 'docpath-brainstorm.md')), true);
    assert.equal(existsSync(join(commandsDir, 'docpath-agent-enter.md')), true);
    assert.equal(existsSync(join(commandsDir, 'docpath-agent-step.md')), true);
    assert.equal(existsSync(join(commandsDir, 'docpath-agent-done.md')), true);
    assert.equal(existsSync(join(commandsDir, 'docpath-agent-handoff.md')), true);
    for (const command of CLAUDE_EXPOSED_COMMANDS) {
      assert.equal(existsSync(join(commandsDir, `docpath-${command}.md`)), true, `${command} slash command should be installed`);
    }
    assert.equal(existsSync(join(commandsDir, 'docpath-link.md')), false, 'link command template should not be installed without a matching CLI command');

    const claude = readFileSync(join(cwd, 'CLAUDE.md'), 'utf-8');
    const shim = readFileSync(join(cwd, '.docpath', 'bin', 'docpath'), 'utf-8');
    const nextCommand = readFileSync(join(commandsDir, 'docpath-next.md'), 'utf-8');
    const brainstormCommand = readFileSync(join(commandsDir, 'docpath-brainstorm.md'), 'utf-8');
    const stepCommand = readFileSync(join(commandsDir, 'docpath-agent-step.md'), 'utf-8');

    assert.match(claude, /\/docpath-next/);
    assert.match(claude, /docpath status --agent/);
    assert.match(shim, /Generated by docpath install/);
    assert.ok((statSync(join(cwd, '.docpath', 'bin', 'docpath')).mode & 0o111) !== 0, 'local shim should be executable');
    assert.match(nextCommand, /\.\/\.docpath\/bin\/docpath next --agent/);
    assert.match(nextCommand, /docpath next --agent/);
    assert.match(brainstormCommand, /\.\/\.docpath\/bin\/docpath brainstorm --input "\$ARGUMENTS"/);
    assert.match(nextCommand, /node \.\/bin\/docpath\.js next --agent/);
    assert.match(stepCommand, /docpath agent step --step "\$ARGUMENTS" --status done/);
    assert.match(stepCommand, /\.\/\.docpath\/bin\/docpath agent step --step "\$ARGUMENTS" --status done/);
    assert.match(stepCommand, /node \.\/bin\/docpath\.js agent step --step "\$ARGUMENTS" --status done/);
    rmSync(cwd, { recursive: true, force: true });
  });

  it('claude command templates use the local shim and do not reference removed commands', () => {
    for (const command of CLAUDE_EXPOSED_COMMANDS) {
      const file = join(TEMPLATE_COMMANDS_DIR, `docpath-${command}.md`);
      assert.equal(existsSync(file), true, `${command} template should exist`);
      const content = readFileSync(file, 'utf-8');
      assert.match(content, /\.\/\.docpath\/bin\/docpath/, `${command} should prefer the local shim`);
      assert.doesNotMatch(content, /docpath link\b/, `${command} should not call nonexistent docpath link`);
    }
    assert.equal(existsSync(join(TEMPLATE_COMMANDS_DIR, 'docpath-link.md')), false);
  });

  it('claude protocol references current lifecycle commands and no removed commands', () => {
    const cwd = mkWorkspace();
    run(`install --cwd ${cwd} --target claude`, cwd);

    const installedClaude = readFileSync(join(cwd, 'CLAUDE.md'), 'utf-8');
    const protocolClaude = readFileSync(join(cwd, '.docpath', 'protocols', 'CLAUDE.md'), 'utf-8');

    for (const content of [installedClaude, protocolClaude]) {
      assert.match(content, /docpath status --agent/);
      assert.match(content, /docpath next --agent/);
      assert.match(content, /docpath agent done/);
      assert.doesNotMatch(content, /docpath link\b/);
      assert.doesNotMatch(content, /docpath archive\b/);
    }

    rmSync(cwd, { recursive: true, force: true });
  });

  it('opencode target installs OPENCODE.md, commands, and OpenCode config only', () => {
    const cwd = mkWorkspace();
    run(`install --cwd ${cwd} --target opencode`, cwd);

    assert.equal(existsSync(join(cwd, 'OPENCODE.md')), true);
    assert.equal(existsSync(join(cwd, 'CLAUDE.md')), false);
    assert.equal(existsSync(join(cwd, 'CODEX.md')), false);
    assert.equal(existsSync(join(cwd, '.opencode', 'commands')), true);
    assert.equal(existsSync(join(cwd, '.opencode', 'docpath.json')), true);

    const agents = readFileSync(join(cwd, 'OPENCODE.md'), 'utf-8');
    assert.match(agents, /docpath status --agent/);
    assert.match(agents, /docpath next --agent/);
    assert.match(agents, /docpath agent done --step/);
    assert.doesNotMatch(agents, /agent enter --step/);
    assert.doesNotMatch(agents, /--auto-next/);

    const opencode = JSON.parse(readFileSync(join(cwd, '.opencode', 'docpath.json'), 'utf-8'));
    assert.equal(opencode.protocol, 'OPENCODE.md');
    assert.equal(opencode.commands.next, 'docpath next --agent');
    assert.equal(opencode.commands.status, 'docpath status --agent');
    rmSync(cwd, { recursive: true, force: true });
  });

  it('codex target installs Codex protocol files and config only', () => {
    const cwd = mkWorkspace();
    run(`install --cwd ${cwd} --target codex`, cwd);

    assert.equal(existsSync(join(cwd, 'AGENTS.md')), true);
    assert.equal(existsSync(join(cwd, 'CODEX.md')), true);
    assert.equal(existsSync(join(cwd, '.codex', 'config.toml')), true);
    assert.equal(existsSync(join(cwd, 'CLAUDE.md')), false);
    assert.equal(existsSync(join(cwd, 'OPENCODE.md')), false);
    assert.equal(existsSync(join(cwd, '.claude', 'commands')), false);
    assert.equal(existsSync(join(cwd, '.opencode', 'docpath.json')), false);

    const agents = readFileSync(join(cwd, 'AGENTS.md'), 'utf-8');
    const codexProtocol = readFileSync(join(cwd, 'CODEX.md'), 'utf-8');
    const codexConfig = readFileSync(join(cwd, '.codex', 'config.toml'), 'utf-8');
    const protocolAgents = readFileSync(join(cwd, '.docpath', 'protocols', 'AGENTS.md'), 'utf-8');

    for (const content of [agents, protocolAgents]) {
      assert.match(content, /docpath status --agent/);
      assert.match(content, /docpath next --agent/);
      assert.match(content, /docpath agent done/);
      assert.doesNotMatch(content, /docpath archive\b/);
    }
    assert.match(codexProtocol, /docpath next --agent/);
    assert.match(codexConfig, /protocol = "CODEX\.md"/);
    assert.match(codexConfig, /fallback_protocol = "AGENTS\.md"/);
    assert.match(codexConfig, /next = "docpath next --agent"/);
    assert.match(codexConfig, /status = "docpath status --agent"/);
    rmSync(cwd, { recursive: true, force: true });
  });

  it('universal target installs all adapter entry files and configs', () => {
    const cwd = mkWorkspace();
    run(`install --cwd ${cwd} --target universal`, cwd);

    assert.equal(existsSync(join(cwd, 'AGENTS.md')), true);
    assert.equal(existsSync(join(cwd, 'CLAUDE.md')), true);
    assert.equal(existsSync(join(cwd, 'CODEX.md')), true);
    assert.equal(existsSync(join(cwd, '.claude', 'commands')), true);
    assert.equal(existsSync(join(cwd, '.opencode', 'commands')), true);
    assert.equal(existsSync(join(cwd, '.codex', 'config.toml')), true);
    assert.equal(existsSync(join(cwd, '.opencode', 'docpath.json')), true);

    const codex = readFileSync(join(cwd, '.codex', 'config.toml'), 'utf-8');
    const protocolAgents = readFileSync(join(cwd, '.docpath', 'protocols', 'AGENTS.md'), 'utf-8');

    assert.match(codex, /next = "docpath next --agent"/);
    assert.match(codex, /status = "docpath status --agent"/);
    assert.match(protocolAgents, /docpath status --agent/);
    assert.match(protocolAgents, /docpath next --agent/);
    assert.match(protocolAgents, /docpath agent done/);
    assert.doesNotMatch(protocolAgents, /docpath archive\b/);
    rmSync(cwd, { recursive: true, force: true });
  });

  it('does not overwrite existing protocol files without --force and prints a diff hint', () => {
    const cwd = mkWorkspace();
    writeFileSync(join(cwd, 'OPENCODE.md'), '# Custom Agent Rules\n\nDo not overwrite.\n');

    const output = run(`install --cwd ${cwd} --target opencode`, cwd);
    const unchanged = readFileSync(join(cwd, 'OPENCODE.md'), 'utf-8');

    assert.match(output, /差异预览/);
    assert.match(output, /使用 --force 覆盖/);
    assert.equal(unchanged, '# Custom Agent Rules\n\nDo not overwrite.\n');

    run(`install --cwd ${cwd} --target opencode --force`, cwd);
    const overwritten = readFileSync(join(cwd, 'OPENCODE.md'), 'utf-8');
    assert.match(overwritten, /docpath next --agent/);
    assert.match(overwritten, /docpath agent done --step/);
    assert.doesNotMatch(overwritten, /agent enter --step/);
    assert.doesNotMatch(overwritten, /Do not overwrite/);
    rmSync(cwd, { recursive: true, force: true });
  });
});
